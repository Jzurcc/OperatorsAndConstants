package com.school.operators;

public class ArithmeticOperators {
    public static void main(String[] args) {
        int a = 48;
        int b = 13;
        System.out.println("48 + 13 = " + (a + b));
        System.out.println("48 - 13 = " + (a - b));
        System.out.println("48 * 13 = " + (a * b));
        System.out.println("48 / 13 = " + (a / b));
        System.out.println("48 % 13 = " + (a % b));
    }
}
